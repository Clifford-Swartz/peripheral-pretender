"""Determinism, style of generated C, device JSON, checked-in files current."""

import json
from pathlib import Path

import pytest

from gen_support import ATDF, OVERLAYS, QEMU, ROOT
from mchpgen import cli, device

JSON_OUT = ROOT / "devices"
REPORT = ROOT / "generator" / "out" / "report-pic32cm5164jh01100.md"


def test_deterministic(dev, overlays, ds, tmp_path):
    again = device.build(dev, overlays)
    a = cli.outputs(ds, str(tmp_path / "q"), str(tmp_path / "d"), str(tmp_path / "r"))
    b = cli.outputs(again, str(tmp_path / "q"), str(tmp_path / "d"),
                    str(tmp_path / "r"))
    assert a == b


def test_c_style(generated):
    for path in (generated / "qemu").rglob("*.h"):
        text = path.read_text(encoding="utf-8")
        assert text.endswith("\n") and "\r" not in text and "\t" not in text
        assert "//" not in text.replace("http://", "").replace("https://", ""), path
        assert "GENERATED by generator/atdf2qemu.py from PIC32CM5164JH01100.atdf" \
            in text
        assert "(PIC32CM-JH_DFP 1.3.221). Do not edit." in text
        assert "SPDX-License-Identifier: GPL-2.0-or-later" in text
        assert "not for submission to upstream QEMU." in text
        long = [l for l in text.splitlines() if len(l) > 80]
        assert not long, (path.name, long[:3])


def test_device_json(generated):
    doc = json.loads((generated / "devices" / "pic32cm5164jh01100.json")
                     .read_text(encoding="utf-8"))
    assert doc["schema"] == "pp-device/1"
    assert len(doc["instances"]) == 55 and len(doc["interrupts"]) == 32
    insts = {i["name"]: i for i in doc["instances"]}
    s4 = insts["SERCOM4"]
    assert (s4["base"], s4["irq"]["line"], s4["ip"]) == (0x42001400, 13,
                                                         "sercom_u2201")
    assert insts["PORT"]["alias"] == {"name": "PORT_IOBUS", "base": 0x60000000,
                                      "size": 0x200}
    sercom = doc["ips"]["sercom_u2201"]
    usart = next(v for v in sercom["views"] if v["mode"] == "USART_INT")
    regs = {r["name"]: r for r in usart["registers"]}
    assert regs["DATA"]["read_side_effect"] is True
    assert regs["STATUS"]["w1c"] == 0x77 and regs["STATUS"]["ro"] == 0x08
    gclk = doc["ips"]["gclk_u2122"]["views"][0]
    assert gclk["reset_overrides"] == [{"key": "GENCTRL[0]", "offset": 0x20,
                                        "size": 4, "value": 0x106}]
    words = {w["addr"]: w["value"] for w in doc["nvm_rows"]["words"]}
    assert words[0x00804000] == 0xB15088FB
    assert doc["core"]["num_irq"] == 32 and doc["core"]["nvic_prio_bits"] == 2


def test_checked_in_outputs_are_current(ds):
    """The committed outputs equal a fresh generation (run the CLI if not)."""
    if not (QEMU / "include").exists():
        pytest.skip("pp-qemu checkout not found")
    files = cli.outputs(ds, str(QEMU), str(JSON_OUT), str(REPORT))
    stale = [p for p, c in files.items()
             if not Path(p).exists() or Path(p).read_text(encoding="utf-8") != c]
    assert not stale, ("regenerate: py generator/atdf2qemu.py --atdf "
                       f"{ATDF} --qemu-out {QEMU} --json-out devices --report "
                       f"{REPORT.relative_to(ROOT)}", stale)
    assert not cli.stale_generated(str(QEMU), files)


def test_cli_check_mode(tmp_path):
    args = ["--atdf", str(ATDF), "--overlays", str(OVERLAYS),
            "--json-out", str(tmp_path)]
    assert cli.main(args + ["--check"]) == 1          # nothing written yet
    assert cli.main(args) == 0
    assert cli.main(args + ["--check"]) == 0
