"""Command line: parse, merge, emit; write only files whose content changed."""

from __future__ import annotations

import argparse
import glob
import os
import sys

from . import (GENERATOR, atdf, avrgen, cgen, device, jsongen, overlay,
               profile, report)
from .overlay import OverlayError

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN_MARKER = f"GENERATED by {GENERATOR}"


def build(atdf_path: str, overlay_dir: str,
          profile_dir: str | None = None) -> device.DeviceSem:
    dev = atdf.parse(atdf_path)
    prof = profile.find(profile_dir or os.path.join(REPO, "profiles"), dev.name)
    return device.build(dev, overlay.load_dir(overlay_dir), prof)


def report_path_for(template: str, ds: device.DeviceSem) -> str:
    """--report may name one file, or contain {device} for several."""
    return template.replace("{device}", ds.symbol)


def outputs(dss, qemu_out: str | None, json_out: str | None,
            report_path: str | None) -> dict[str, str]:
    """Absolute path -> file content for every requested output.

    @dss is one DeviceSem or a list of them. The per-IP constant headers
    are shared by every device that has the IP; everything else is per
    device.
    """
    if isinstance(dss, device.DeviceSem):
        dss = [dss]
    if report_path and len(dss) > 1 and "{device}" not in report_path:
        raise ValueError("--report needs {device} when several ATDFs are given")
    files = {}
    if qemu_out:
        by_key: dict[str, list] = {}
        for ds in dss:
            for ip in ds.ips.values():
                if cgen.wants_ip_header(ip):
                    by_key.setdefault(ip.key, []).append((ds, ip))
                    if ip.views:
                        files[os.path.join(qemu_out, cgen.ip_tables_path(ds, ip))] = \
                            cgen.ip_tables(ds, ip)
            if ds.device.is_avr:
                files[os.path.join(qemu_out, avrgen.soc_header_path(ds))] = \
                    avrgen.soc_header(ds)
                files[os.path.join(qemu_out, avrgen.device_header_path(ds))] = \
                    avrgen.device_header(ds)
                continue
            files[os.path.join(qemu_out, cgen.soc_header_path(ds))] = \
                cgen.soc_header(ds)
            files[os.path.join(qemu_out, cgen.nvmrows_header_path(ds))] = \
                cgen.nvmrows_header(ds)
            files[os.path.join(qemu_out, cgen.device_header_path(ds))] = \
                cgen.device_header(ds)
        for key, entries in by_key.items():
            files[os.path.join(qemu_out, cgen.ip_header_path(entries[0][1]))] = \
                cgen.ip_header(entries)
    for ds in dss:
        if json_out:
            files[os.path.join(json_out, f"{ds.symbol}.json")] = \
                jsongen.device_json(ds)
        if report_path:
            files[report_path_for(report_path, ds)] = report.report(ds)
    return {os.path.abspath(p): c for p, c in sorted(files.items())}


def stale_generated(qemu_out: str | None, files: dict[str, str]) -> list[str]:
    """Generated IP headers left over from earlier runs."""
    if not qemu_out:
        return []
    out = []
    gen = os.path.join(qemu_out, "include", "hw", "mchp", "gen")
    for path in sorted(glob.glob(os.path.join(gen, "*.h")) +
                       glob.glob(os.path.join(gen, "*", "*.h"))):
        path = os.path.abspath(path)
        if path not in files:
            with open(path, encoding="utf-8") as f:
                if GEN_MARKER in f.read():
                    out.append(path)
    return out


def _read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read()
    except FileNotFoundError:
        return None


def _write(path: str, content: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="atdf2qemu.py",
        description="Generate QEMU register tables and device descriptions "
                    "from a Microchip ATDF plus behavior overlays.")
    ap.add_argument("--atdf", required=True, action="append",
                    help="device .atdf file; repeat for several devices, "
                         "which then share the per-IP constant headers")
    ap.add_argument("--overlays", default=os.path.join(REPO, "overlays"),
                    help="overlay directory (default: %(default)s)")
    ap.add_argument("--profiles", default=os.path.join(REPO, "profiles"),
                    help="device profile directory (default: %(default)s)")
    ap.add_argument("--qemu-out", help="pp-qemu source root for C headers")
    ap.add_argument("--json-out", help="directory for <device>.json")
    ap.add_argument("--report", help="markdown report path; with several "
                                     "ATDFs it must contain {device}")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if any output is missing or stale")
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="print every diagnostic")
    args = ap.parse_args(argv)
    try:
        dss = [build(a, args.overlays, args.profiles) for a in args.atdf]
        files = outputs(dss, args.qemu_out, args.json_out, args.report)
    except (OverlayError, ValueError, KeyError) as e:
        print(f"atdf2qemu: error: {e}", file=sys.stderr)
        return 2
    stale = stale_generated(args.qemu_out, files)
    changed = [p for p, c in files.items() if _read(p) != c]
    for ds in dss:
        for d in ds.diags:
            if args.verbose or d.level == "warning":
                print(f"{d.level}: {ds.device.name}: {d.where}: {d.msg}",
                      file=sys.stderr)
    if args.check:
        for p in changed:
            print(f"stale: {p}")
        for p in stale:
            print(f"unexpected generated file: {p}")
        return 1 if changed or stale else 0
    for p in changed:
        _write(p, files[p])
    for p in stale:
        os.remove(p)
    names = ", ".join(ds.device.name for ds in dss)
    warnings = sum(d.level == "warning" for ds in dss for d in ds.diags)
    print(f"atdf2qemu: {names}: {len(files)} outputs, {len(changed)} "
          f"written, {len(stale)} stale removed, {warnings} warnings")
    return 0
