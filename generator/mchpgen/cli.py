"""Command line: parse, merge, emit; write only files whose content changed."""

from __future__ import annotations

import argparse
import glob
import os
import sys

from . import GENERATOR, atdf, cgen, device, jsongen, overlay, report
from .overlay import OverlayError

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN_MARKER = f"GENERATED by {GENERATOR}"


def build(atdf_path: str, overlay_dir: str) -> device.DeviceSem:
    return device.build(atdf.parse(atdf_path), overlay.load_dir(overlay_dir))


def outputs(ds: device.DeviceSem, qemu_out: str | None, json_out: str | None,
            report_path: str | None) -> dict[str, str]:
    """Absolute path -> file content for every requested output."""
    files = {}
    if qemu_out:
        for ip in ds.ips.values():
            if cgen.wants_ip_header(ip):
                files[os.path.join(qemu_out, cgen.ip_header_path(ip))] = \
                    cgen.ip_header(ds, ip)
        files[os.path.join(qemu_out, cgen.soc_header_path(ds))] = cgen.soc_header(ds)
        files[os.path.join(qemu_out, cgen.nvmrows_header_path(ds))] = \
            cgen.nvmrows_header(ds)
    if json_out:
        files[os.path.join(json_out, f"{ds.symbol}.json")] = jsongen.device_json(ds)
    if report_path:
        files[report_path] = report.report(ds)
    return {os.path.abspath(p): c for p, c in sorted(files.items())}


def stale_generated(qemu_out: str | None, files: dict[str, str]) -> list[str]:
    """Generated IP headers left over from earlier runs."""
    if not qemu_out:
        return []
    out = []
    for path in sorted(glob.glob(os.path.join(qemu_out, "include", "hw", "mchp",
                                              "gen", "*.h"))):
        path = os.path.abspath(path)
        if path not in files:
            with open(path, encoding="utf-8") as f:
                if GEN_MARKER in f.read():
                    out.append(path)
    return out


def _read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read()
    except FileNotFoundError:
        return None


def _write(path: str, content: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="atdf2qemu.py",
        description="Generate QEMU register tables and device descriptions "
                    "from a Microchip ATDF plus behavior overlays.")
    ap.add_argument("--atdf", required=True, help="device .atdf file")
    ap.add_argument("--overlays", default=os.path.join(REPO, "overlays"),
                    help="overlay directory (default: %(default)s)")
    ap.add_argument("--qemu-out", help="pp-qemu source root for C headers")
    ap.add_argument("--json-out", help="directory for <device>.json")
    ap.add_argument("--report", help="markdown report path")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if any output is missing or stale")
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="print every diagnostic")
    args = ap.parse_args(argv)
    try:
        ds = build(args.atdf, args.overlays)
        files = outputs(ds, args.qemu_out, args.json_out, args.report)
    except (OverlayError, ValueError, KeyError) as e:
        print(f"atdf2qemu: error: {e}", file=sys.stderr)
        return 2
    stale = stale_generated(args.qemu_out, files)
    changed = [p for p, c in files.items() if _read(p) != c]
    for d in ds.diags:
        if args.verbose or d.level == "warning":
            print(f"{d.level}: {d.where}: {d.msg}", file=sys.stderr)
    if args.check:
        for p in changed:
            print(f"stale: {p}")
        for p in stale:
            print(f"unexpected generated file: {p}")
        return 1 if changed or stale else 0
    for p in changed:
        _write(p, files[p])
    for p in stale:
        os.remove(p)
    print(f"atdf2qemu: {ds.device.name}: {len(files)} outputs, {len(changed)} "
          f"written, {len(stale)} stale removed, "
          f"{sum(d.level == 'warning' for d in ds.diags)} warnings")
    return 0
