# NVM rows image


def nvmrows_header_path(ds: DeviceSem) -> str:
    return f"hw/arm/{ds.symbol}_nvmrows.h"


def nvmrows_header(ds: DeviceSem) -> str:
    sym, SYM = ds.symbol, ds.symbol.upper()
    g = guard(nvmrows_header_path(ds))
    last = nvmrows.BASE + nvmrows.SIZE - 1
    out = file_header(f"{ds.device.name} default NVM rows image "
                      f"(0x{nvmrows.BASE:08X}-0x{last:08X})", ds,
                      ["Calibration and serial-number values are placeholders;",
                       "dump real ones from silicon before trusting them."])
    out += [f"#ifndef {g}", f"#define {g}", "", '#include "qemu/bswap.h"', "",
            define(f"{SYM}_NVMROWS_BASE", f"0x{nvmrows.BASE:08X}"),
            define(f"{SYM}_NVMROWS_SIZE", f"0x{nvmrows.SIZE:X}")]
    for s in sorted(ds.device.memory_segments, key=lambda s: s.start):
        if s.type in ("fuses", "user_page") and s.address_space == "base":
            out.append(define(f"{SYM}_NVMROWS_{s.name}_OFFSET",
                              f"0x{s.start - nvmrows.BASE:04X}"))
    rows = ds.profile.nvm_rows
    user0, user1 = rows.user_row
    out += ["", f"/* Production user row (profiles/{ds.profile.file}) */",
            define(f"{SYM}_USER_ROW_WORD0", f"0x{user0:08X}"),
            define(f"{SYM}_USER_ROW_WORD1", f"0x{user1:08X}"), "",
            "/* Serial number word addresses (DS 10.3) and default value */",
            f"static const uint32_t {sym}_serial_addr[4] = {{"]
    out += wrap_items([f"0x{a:08X}" for a in rows.serial_addrs], "    ")
    out += ["};", f"static const uint32_t {sym}_serial_default[4] = {{"]
    out += wrap_items([f"0x{v:08X}" for v in rows.serial_default], "    ")
    fn = f"static inline void {sym}_nvmrows_fill("
    out += ["};", "", "/*",
            f" * Fill @buf ({SYM}_NVMROWS_SIZE bytes, mapped at",
            f" * {SYM}_NVMROWS_BASE) with the default image: erased (0xFF)",
            " * rows, production user row, NVM geometry in OTP1, a plausible",
            " * calibration row, and @serial as the four serial-number words.",
            " */",
            f"{fn}uint8_t *buf,", " " * len(fn) + "const uint32_t serial[4])",
            "{", "    static const struct {", "        uint32_t addr;",
            "        uint32_t value;", "    } words[] = {"]
    for w in nvmrows.default_words(ds.device, rows):
        out += [f"        /* {w.what} */",
                f"        {{ 0x{w.addr:08X}, 0x{w.value:08X} }},"]
    out += ["    };", f"    const uint32_t base = {SYM}_NVMROWS_BASE;",
            "    unsigned i;", "",
            f"    memset(buf, 0x{nvmrows.FILL:02X}, {SYM}_NVMROWS_SIZE);",
            "    for (i = 0; i < ARRAY_SIZE(words); i++) {",
            "        stl_le_p(buf + words[i].addr - base, words[i].value);",
            "    }", "    for (i = 0; i < 4; i++) {",
            f"        stl_le_p(buf + {sym}_serial_addr[i] - base, serial[i]);",
            "    }", "}", "", f"#endif /* {g} */"]
    return "\n".join(out) + "\n"
