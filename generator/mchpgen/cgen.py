def _inst_entry(ds: DeviceSem, i: InstanceSem) -> list[str]:
    items = [f".name = {c_str(i.name)}", f".module = {c_str(i.module)}",
             f".ip_id = {c_str(i.ip_id)}", f".ip_version = {c_str(i.ip_version)}",
             f".base = 0x{i.base:08X}", f".slot_size = 0x{i.slot_size:X}"]
    if i.alias_name:
        items += [f".alias_name = {c_str(i.alias_name)}",
                  f".alias_base = 0x{i.alias_base:08X}",
                  f".alias_size = 0x{i.alias_size:X}"]
    items += [f".irq = {i.irq}", f".irq_input = {i.irq_input}",
              f".pac_id = {i.pac_id}", f".gclk_core = {i.gclk_core}",
              f".gclk_slow = {i.gclk_slow}", f".dmac_rx = {i.dmac_rx}",
              f".dmac_tx = {i.dmac_tx}",
              ".flags = " + (" | ".join(f"MCHP_INST_{f}" for f in i.flags) or "0")]
    ip = i.ip
    if ip.views and not ip.core:
        view = ip.view(ip.default_view)
        tp = ip.table_prefix(view)
        items += [f".regs_size = MCHP_{ip.cname}_SIZE",
                  f".regs = mchp_{tp.lower()}_regs", f".nregs = MCHP_{tp}_NREGS"]
        if view.overrides:
            items += [f".ovr = mchp_{tp.lower()}_reset_overrides",
                      f".novr = MCHP_{tp}_NRESET_OVERRIDES"]
        if ip.selector:
            items += [f".views = mchp_{ip.cname.lower()}_views",
                      f".nviews = MCHP_{ip.cname}_NVIEWS",
                      f".view_sel_offset = MCHP_{ip.cname}_VIEW_SEL_OFFSET",
                      f".view_sel_shift = MCHP_{ip.cname}_VIEW_SEL_SHIFT",
                      f".view_sel_length = MCHP_{ip.cname}_VIEW_SEL_LENGTH"]
        if view.reset_from:
            items += [f".reset_from = mchp_{tp.lower()}_reset_from",
                      f".nreset_from = MCHP_{tp}_NRESET_FROM"]
    return struct_entry(items)


def soc_header_path(ds: DeviceSem) -> str:
    return f"include/hw/arm/{ds.symbol}_gen.h"


def soc_header(ds: DeviceSem) -> str:
    dev = ds.device
    sym, SYM = ds.symbol, ds.symbol.upper()
    path = soc_header_path(ds)
    g = guard(path[len("include/"):])
    out = file_header(f"{dev.name} SoC description: memory map, instances, "
                      f"IRQs, signals", ds)
    out += [f"#ifndef {g}", f"#define {g}", "", '#include "hw/mchp/mchp_device.h"']
    for ip in sorted(ds.ips.values(), key=lambda x: x.key):
        if wants_ip_header(ip) and ip.views:
            out.append(f'#include "{ip_header_path(ip)[len("include/"):]}"')
    p = dev.params
    out += ["", "/* Core configuration (ATDF device parameters) */",
            define(f"{SYM}_NUM_IRQ", p["NUM_IRQ"]),
            define(f"{SYM}_NVIC_PRIO_BITS", p["__NVIC_PRIO_BITS"]),
            define(f"{SYM}_CM0P_REV", p["__CM0P_REV"]),
            define(f"{SYM}_MPU_PRESENT", p["__MPU_PRESENT"]),
            define(f"{SYM}_VTOR_PRESENT", p["__VTOR_PRESENT"])]
    sig = dev.property_groups.get("SIGNATURES", {})
    if "DSU_DID" in sig:
        out.append(define(f"{SYM}_DSU_DID_SIGNATURE", sig["DSU_DID"],
                          "compare under mask 0xFFFFF0FF"))
    out += ["", "/* Memory segments */"]
    segs = sorted((s for s in dev.memory_segments if s.address_space == "base"),
                  key=lambda s: (s.start, s.name))
    for s in segs:
        out += [define(f"{SYM}_{s.name}_BASE", f"0x{s.start:08X}"),
                define(f"{SYM}_{s.name}_SIZE", f"0x{s.size:X}")]
    out += ["", f"static const MchpMemSegment {sym}_mem_segments[] = {{"]
    for s in segs:
        out += struct_entry([f".name = {c_str(s.name)}", f".base = 0x{s.start:08X}",
                             f".size = 0x{s.size:X}", f".type = {c_str(s.type)}",
                             f".writable = {'true' if 'W' in s.rw else 'false'}",
                             f".exec = {'true' if s.exec else 'false'}"])
    out += ["};", define(f"{SYM}_NUM_MEM_SEGMENTS", str(len(segs))), ""]
    out += ["/*", " * Peripheral instances, by address. CORE instances are provided"
            " by armv7m,", " * FUSES lives in the NVM rows ROM; neither is mapped"
            " as MMIO.", " */"]
    for n, i in enumerate(ds.instances):
        out.append(define(f"{SYM}_INST_{i.name.upper()}", str(n)))
    out += ["", f"static const MchpInstanceInfo {sym}_instances[] = {{"]
    for i in ds.instances:
        out += _inst_entry(ds, i)
    out += ["};", define(f"{SYM}_NUM_INSTANCES", str(len(ds.instances))), ""]
    out += ["/* NVIC lines; nsources > 1 means an OR gate (MchpInstanceInfo."
            "irq_input) */", f"static const MchpIrqLine {sym}_irq_lines[] = {{"]
    for line in ds.irqs:
        out += struct_entry([f".name = {c_str(line.name)}", f".line = {line.index}",
                             f".nsources = {len(line.instances)}"])
    out += ["};", define(f"{SYM}_NUM_IRQ_LINES", str(len(ds.irqs))), ""]
    out += _refs_lines(f"{sym}_gclk_channels", "GCLK peripheral channel users",
                       ds.gclk_users, f"{SYM}_NUM_GCLK_CHANNEL_USERS")
    out += _refs_lines(f"{sym}_dmac_triggers", "DMAC trigger sources",
                       ds.dmac_triggers, f"{SYM}_NUM_DMAC_TRIGGERS")
    out += ["/* Pad signals (PMUX function letters A..K map to pmux 0..10) */",
            f"static const MchpSignalInfo {sym}_signals[] = {{"]
    for s in ds.signals:
        out += struct_entry([f".instance = {c_str(s.instance)}",
                             f".group = {c_str(s.group)}", f".index = {s.index}",
                             f".function = {c_str(s.function)}", f".pmux = {s.pmux}",
                             f".pad = {c_str(s.pad)}", f".pin = {s.pin}"])
    out += ["};", define(f"{SYM}_NUM_SIGNALS", str(len(ds.signals))), "",
            f"#endif /* {g} */"]
    return "\n".join(out) + "\n"


def _refs_lines(table: str, title: str, refs, count: str) -> list[str]:
    out = [f"/* {title} (ATDF instance parameters) */",
           f"static const MchpPeriphRef {table}[] = {{"]
    for r in refs:
        out += struct_entry([f".id = {r.id}", f".instance = {c_str(r.instance)}",
                             f".param = {c_str(r.param)}"])
    return out + ["};", define(count, str(len(refs))), ""]


