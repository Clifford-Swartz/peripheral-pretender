WIDTH = 80
IDENT = re.compile(r"[^A-Za-z0-9_]")


def hexw(value: int, size: int) -> str:
    """Hex literal with 2 digits per register byte: 0x0B, 0x00000106."""
    return f"0x{value:0{2 * size}X}"


def c_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def wrap_items(items: list[str], indent: str) -> list[str]:
    """Join 'key = value' items with ', ' into lines of at most WIDTH."""
    lines, cur = [], ""
    for item in items:
        piece = item + ","
        if len(indent) + len(piece) > WIDTH and " | " in piece:
            # An OR of flags too long for one line: break after a '|'
            if cur:
                lines.append(indent + cur)
                cur = ""
            terms = piece.split(" | ")
            line, pad = "", indent
            for i, term in enumerate(terms):
                term += "" if i == len(terms) - 1 else " |"
                if line and len(pad) + len(line) + 1 + len(term) > WIDTH:
                    lines.append(pad + line)
                    line, pad = term, indent + "    "
                else:
                    line = f"{line} {term}" if line else term
            lines.append(pad + line)
            continue
        if cur and len(indent) + len(cur) + 1 + len(piece) > WIDTH:
            lines.append(indent + cur)
            cur = piece
        else:
            cur = f"{cur} {piece}" if cur else piece
    if cur:
        lines.append(indent + cur)
    return lines


def struct_entry(items: list[str], indent: str = "    ") -> list[str]:
    one = f"{indent}{{ {', '.join(items)} }},"
    if len(one) <= WIDTH:
        return [one]
    return [indent + "{"] + wrap_items(items, indent + "    ") + [indent + "},"]


def file_header(title: str, ds: DeviceSem, extra: list[str] = ()) -> list[str]:
    dev = ds.device
    lines = ["/*", f" * {title}", " *",
             " * Peripheral Pretender: a personal project. AI-assisted code;",
             " * not for submission to upstream QEMU.", " *",
             f" * GENERATED by {GENERATOR} from {dev.atdf_file}",
             f" * ({dev.dfp_name} {dev.dfp_version}). Do not edit."]
    lines += [f" * {e}" for e in extra]
    lines += [" *", " * SPDX-License-Identifier: GPL-2.0-or-later", " */", ""]
    return lines


def _file_header_multi(title: str, dss: list[DeviceSem],
                       extra: list[str] = ()) -> list[str]:
    lines = ["/*", f" * {title}", " *",
             " * Peripheral Pretender: a personal project. AI-assisted code;",
             " * not for submission to upstream QEMU.", " *",
             f" * GENERATED by {GENERATOR} from"]
    lines += [f" * {ds.device.atdf_file} ({ds.device.dfp_name} "
              f"{ds.device.dfp_version})" for ds in dss]
    lines += [" * Do not edit."]
    lines += [f" * {e}" for e in extra]
    lines += [" *", " * SPDX-License-Identifier: GPL-2.0-or-later", " */", ""]
    return lines


def guard(path: str) -> str:
    return IDENT.sub("_", path.upper())


def define(name: str, value: str, comment: str = "") -> str:
    line = f"#define {name} {value}"
    if len(line) > WIDTH:
        line = f"#define {name} \\\n    {value}"
    if comment:
        cand = f"{line} /* {comment} */"
        if len(cand) <= WIDTH and "\n" not in line:
            return cand
        return f"/* {comment} */\n{line}"
    return line


def macro_call(name: str, args: list[str], indent: str = "") -> str:
    """NAME(a, b, c), continued after the first argument when too long."""
    line = f"{indent}{name}({', '.join(args)})"
    if len(line) <= WIDTH:
        return line
    cont = " " * (len(indent) + len(name) + 1)
    return f"{indent}{name}({args[0]},\n{cont}{', '.join(args[1:])})"


