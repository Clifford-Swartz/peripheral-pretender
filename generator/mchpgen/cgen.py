def _value_name(name: str) -> str:
    return IDENT.sub("_", name).upper()


def _scope_lines(scope: ConstScope) -> list[str]:
    out = []
    if scope.count:
        out += [define(f"{scope.prefix}_OFFSET", f"0x{scope.offset:02X}"),
                define(f"{scope.prefix}_STRIDE", f"0x{scope.stride:02X}"),
                define(f"{scope.prefix}_COUNT", str(scope.count))]
    for rc in scope.regs:
        reg = f"{scope.prefix}_{rc.name}"
        out.append(macro_call(f"REG{rc.size * 8}", [reg, f"0x{rc.offset:02X}"]))
        for f in rc.fields:
            out.append(macro_call("FIELD", [reg, f.name, str(f.shift),
                                            str(f.width)], "    "))
        if rc.count > 1:
            out.append(define(f"{reg}_COUNT", str(rc.count)))
        seen = set()
        for f in rc.fields:
            for v in f.values:
                name = f"{reg}_{f.name}_{_value_name(v.name)}"
                if name in seen:
                    raise ValueError(f"duplicate value constant {name}")
                seen.add(name)
                out.append(define(name, f"0x{v.value:X}"))
    return out


def _reg_entry(r: RegSem, regs: list[RegSem]) -> list[str]:
    items = [f".name = {c_str(r.name)}", f".offset = 0x{r.offset:02X}",
             f".size = {r.size}", f".count = {r.count}", f".stride = {r.stride}"]
    if r.alias_index >= 0:
        items.append(f".alias_of = {r.alias_index} /* {regs[r.alias_index].name} */")
    else:
        items.append(".alias_of = -1")
    items += [f".reset = {hexw(r.reset, r.size)}", f".impl = {hexw(r.impl, r.size)}",
              f".wmask = {hexw(r.wmask, r.size)}"]
    for key in ("w1c", "rdz", "enprot"):
        if getattr(r, key):
            items.append(f".{key} = {hexw(getattr(r, key), r.size)}")
    if r.syncbusy:
        note = r.sync_reg[len(r.scope):] if r.sync_reg else ""
        note += ", << element" if r.sync_per_element else ""
        items.append(f".syncbusy = 0x{r.syncbusy:08X} /* {note} */")
    flags = " | ".join(f"MCHP_F_{f}" for f in r.flags) or "0"
    items.append(f".flags = {flags}")
    return struct_entry(items)


def _table_name(ds: DeviceSem, ip: IpSem, view: ViewSem, kind: str) -> str:
    """C name of a per-device table: <device>_<ip>[_<mode>]_<kind>."""
    return f"{ds.symbol}_{ip.table_prefix(view).lower()}_{kind}"


def _count_name(ds: DeviceSem, ip: IpSem, view: ViewSem, kind: str) -> str:
    return f"{ds.symbol.upper()}_{ip.table_prefix(view)}_{kind}"


def _view_consts(view: ViewSem) -> list[str]:
    title = view.mode + (f": {view.caption}" if view.caption else "")
    out = [f"/* {title} */", ""] if view.mode else []
    for scope in view.consts:
        out += _scope_lines(scope) + [""]
    return out


def _view_tables(ds: DeviceSem, ip: IpSem, view: ViewSem) -> list[str]:
    out = [f"/* {view.mode} */"] if view.mode else []
    out.append(f"static const MchpRegInfo "
               f"{_table_name(ds, ip, view, 'regs')}[] = {{")
    for r in view.regs:
        out += _reg_entry(r, view.regs)
    out += ["};", define(_count_name(ds, ip, view, "NREGS"),
                         str(len(view.regs))), ""]
    if view.overrides:
        out.append(f"static const MchpResetOverride "
                   f"{_table_name(ds, ip, view, 'reset_overrides')}[] = {{")
        for o in view.overrides:
            out += struct_entry([f".offset = 0x{o.offset:02X}", f".size = {o.size}",
                                 f".value = {hexw(o.value, o.size)}"])
            out[-1] += f" /* {o.key} */"
        out += ["};", define(_count_name(ds, ip, view, "NRESET_OVERRIDES"),
                             str(len(view.overrides))), ""]
    if view.reset_from:
        out.append(f"static const MchpFuseReset "
                   f"{_table_name(ds, ip, view, 'reset_from')}[] = {{")
        for fr in view.reset_from:
            out.append(f"    /* {fr.key} <- {'NOT ' if fr.invert else ''}{fr.fuse} */")
            out += struct_entry([f".fuse_addr = 0x{fr.fuse_addr:08X}",
                                 f".fuse_mask = 0x{fr.fuse_mask:08X}",
                                 f".reg_offset = 0x{fr.reg_offset:02X}",
                                 f".reg_size = {fr.reg_size}",
                                 f".reg_mask = {hexw(fr.reg_mask, fr.reg_size)}",
                                 f".invert = {'true' if fr.invert else 'false'}"])
        out += ["};", define(_count_name(ds, ip, view, "NRESET_FROM"),
                             str(len(view.reset_from))), ""]
    return out


def _selector_consts(ip: IpSem) -> list[str]:
    sel = ip.selector
    out = ["/*",
           f" * Register views (ATDF register-group modes), selected by "
           f"{sel.register}.{sel.field}",
           " */",
           define(f"MCHP_{ip.cname}_VIEW_SEL_OFFSET", f"0x{sel.offset:02X}"),
           define(f"MCHP_{ip.cname}_VIEW_SEL_SHIFT", str(sel.shift)),
           define(f"MCHP_{ip.cname}_VIEW_SEL_LENGTH", str(sel.width))]
    for v in ip.views:
        out.append(define(f"MCHP_{ip.cname}_{sel.field}_{v.mode}", str(v.value)))
    return out + [""]


def _views_table(ds: DeviceSem, ip: IpSem) -> list[str]:
    sym, SYM = ds.symbol, ds.symbol.upper()
    out = [f"/* Register views; {SYM}_{ip.cname}_DEFAULT_VIEW: at reset */",
           f"static const MchpRegView {sym}_{ip.cname.lower()}_views[] = {{"]
    for v in ip.views:
        items = [f".name = {c_str(v.mode)}", f".value = {v.value}",
                 f".regs = {_table_name(ds, ip, v, 'regs')}",
                 f".nregs = {_count_name(ds, ip, v, 'NREGS')}"]
        if v.overrides:
            items += [f".ovr = {_table_name(ds, ip, v, 'reset_overrides')}",
                      f".novr = {_count_name(ds, ip, v, 'NRESET_OVERRIDES')}"]
        out += struct_entry(items)
    default = [v.mode for v in ip.views].index(ip.default_view)
    out += ["};", define(f"{SYM}_{ip.cname}_NVIEWS", str(len(ip.views))),
            define(f"{SYM}_{ip.cname}_DEFAULT_VIEW", str(default),
                   ip.default_view), ""]
    return out


# -- merging the constants of several devices --------------------------------


def _merge_field(where: str, a: FieldDef, b: FieldDef) -> FieldDef | None:
    """The FIELD() covering @a and @b, or None if they sit at different bits
    (e.g. MCLK clock-mask bits): a shared constant would be wrong somewhere,
    so it is left out and a model needing it fails to compile."""
    if a.shift != b.shift:
        return None
    # Same position, different width: the wider field covers both devices;
    # each device's register table still masks what it implements.
    top = max(a.mask.bit_length(), b.mask.bit_length())
    mask = ((1 << top) - 1) & ~((1 << a.shift) - 1)
    # A value name that means different things on different devices (e.g.
    # DSU.DID.DEVSEL part numbers) is left out: no model can rely on it.
    vals = {v.name: v for v in a.values}
    clash = {v.name for v in b.values
             if v.name in vals and vals[v.name].value != v.value}
    for v in b.values:
        vals.setdefault(v.name, v)
    return FieldDef(a.name, mask, a.caption,
                    [v for n, v in vals.items() if n not in clash])


def _merge_reg(where: str, a: RegConst, b: RegConst) -> RegConst:
    if a.offset != b.offset:
        raise ValueError(f"{where}_{a.name}: offset 0x{a.offset:X} on one "
                         f"device and 0x{b.offset:X} on another")
    fields = {f.name: f for f in a.fields}
    dropped = set()
    for f in b.fields:
        if f.name in fields:
            merged = _merge_field(f"{where}_{a.name}", fields[f.name], f)
            if merged is None:
                dropped.add(f.name)
            else:
                fields[f.name] = merged
        else:
            fields[f.name] = f
    fields = {n: f for n, f in fields.items() if n not in dropped}
    first = {f.name: n for n, f in enumerate(a.fields)}
    order = sorted(fields.values(),
                   key=lambda f: (first.get(f.name, len(first)), f.shift, f.name))
    # A register widened on one device: the wider constant covers both.
    return RegConst(a.name, a.offset, max(a.size, b.size),
                    max(a.count, b.count), order)


def _merge_scope(a: ConstScope, b: ConstScope) -> ConstScope:
    if (a.offset, a.stride) != (b.offset, b.stride) and a.count and b.count:
        raise ValueError(f"{a.prefix}: subgroup layout differs between devices")
    regs = {r.name: r for r in a.regs}
    for r in b.regs:
        regs[r.name] = (_merge_reg(a.prefix, regs[r.name], r)
                        if r.name in regs else r)
    first = {r.name: n for n, r in enumerate(a.regs)}
    # Registers of the first device keep their order; others go by offset.
    order = sorted(regs.values(),
                   key=lambda r: (r.offset if r.name not in first else
                                  a.regs[first[r.name]].offset,
                                  first.get(r.name, len(first)), r.name))
    return ConstScope(a.prefix, order, a.offset or b.offset,
                      a.stride or b.stride, max(a.count, b.count))


def _merge_scopes(lists: list[list[ConstScope]]) -> list[ConstScope]:
    merged: dict[str, ConstScope] = {}
    for scopes in lists:
        for sc in scopes:
            merged[sc.prefix] = (_merge_scope(merged[sc.prefix], sc)
                                 if sc.prefix in merged else sc)
    return list(merged.values())


def _merged_view_consts(ips: list[IpSem]) -> list[str]:
    modes: dict[str, list[ViewSem]] = {}
    for ip in ips:
        for v in ip.views:
            modes.setdefault(v.mode, []).append(v)
    out = []
    for views in modes.values():
        first = views[0]
        out += _view_consts(ViewSem(first.mode, first.value, first.caption,
                                    [], [], [], None,
                                    _merge_scopes([v.consts for v in views])))
    return out


def _merged_selector_consts(ips: list[IpSem]) -> list[str]:
    with_sel = [ip for ip in ips if ip.selector]
    if not with_sel:
        return []
    sels = {(ip.selector.offset, ip.selector.shift, ip.selector.width)
            for ip in with_sel}
    if len(sels) > 1:
        raise ValueError(f"{ips[0].cname}: view selector differs between "
                         f"devices")
    out = _selector_consts(with_sel[0])
    seen = set(out)
    for ip in with_sel[1:]:
        for line in _selector_consts(ip):
            if line.startswith("#define") and line not in seen:
                out.insert(len(out) - 1, line)
                seen.add(line)
    return out


def ip_header_path(ip: IpSem) -> str:
    return f"include/hw/mchp/gen/{ip.key}.h"


def ip_tables_path(ds: DeviceSem, ip: IpSem) -> str:
    return f"include/hw/mchp/gen/{ds.symbol}/{ip.key}.h"


def wants_ip_header(ip: IpSem) -> bool:
    return not ip.core and bool(ip.views or ip.extra_consts)


def _overlay_line(ip: IpSem) -> str:
    if ip.overlay and ip.overlay_status == "applied":
        return f"Overlay: overlays/{ip.overlay.file} (sha1 {ip.overlay.sha1[:12]})"
    if ip.overlay:
        return (f"Overlay overlays/{ip.overlay.file} NOT applied "
                f"(version mismatch): heuristics only")
    return "No overlay: ATDF facts and heuristics only"


def ip_header(entries: list[tuple[DeviceSem, IpSem]]) -> str:
    """REG/FIELD constants of one IP, merged over every device that has it.

    Models compile once against these; each device's register tables
    (ip_tables) say which registers and bits that device implements.
    """
    ip0 = entries[0][1]
    ips = [ip for _, ip in entries]
    mod = ip0.module
    versions = sorted({ip.module.version for ip in ips})
    path = ip_header_path(ip0)
    g = guard(path[len("include/"):])
    title = (f"{mod.name} {mod.id} {', '.join(versions)} register constants "
             f"({mod.caption or mod.name})")
    extra = []
    if len(title) + 3 > WIDTH:
        title = f"{mod.name} {mod.id} {', '.join(versions)} register constants"
        extra.append(mod.caption or mod.name)
    extra.append(f"Devices: {', '.join(ds.device.name for ds, _ in entries)}")
    extra += sorted({_overlay_line(ip) for ip in ips})
    out = _file_header_multi(title, [ds for ds, _ in entries], extra)
    out += [f"#ifndef {g}", f"#define {g}", "",
            '#include "hw/core/registerfields.h"', ""]
    out += _merged_view_consts(ips)
    out += _merged_selector_consts(ips)
    extras = _merge_scopes([ip.extra_consts for ip in ips])
    if extras:
        out += ["/* Memory-resident structures and fuse rows: constants only */",
                ""]
        for scope in extras:
            out += _scope_lines(scope) + [""]
    out.append(f"#endif /* {g} */")
    return "\n".join(out) + "\n"


def ip_tables(ds: DeviceSem, ip: IpSem) -> str:
    """The register tables of one IP on one device."""
    mod = ip.module
    path = ip_tables_path(ds, ip)
    g = guard(path[len("include/"):])
    out = file_header(f"{ds.device.name} {mod.name} {mod.id} {mod.version} "
                      f"register tables", ds, [_overlay_line(ip)])
    out += [f"#ifndef {g}", f"#define {g}", "",
            f'#include "{ip_header_path(ip)[len("include/"):]}"',
            '#include "hw/misc/mchp_regfile.h"']
    if ip.selector or any(v.reset_from for v in ip.views):
        out.append('#include "hw/mchp/mchp_device.h"')
    out += ["", define(f"{ds.symbol.upper()}_{ip.cname}_REGS_SIZE",
                       f"0x{ip.size:X}", "register file bytes"), ""]
    for view in ip.views:
        out += _view_tables(ds, ip, view)
    if ip.selector:
        out += _views_table(ds, ip)
    out.append(f"#endif /* {g} */")
    return "\n".join(out) + "\n"


